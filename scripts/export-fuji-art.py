#!/usr/bin/env python3
"""Export the hand-drawn Fuji plate (owner 2026-10-23) for home section 4 (components/v3/fuji-climb.tsx).

Source: My Drive/SNOBI/Art/Fuji/fuji-plate-source-2026-10-23.webp (1491x1055, painted paper ground).
Steps:
  1. The staff (金剛杖) is cleaned: its painted stamps are replaced by clean staff rows from higher up, so the page can
     burn the stamps in at each farm's true height (the painting had them at rough heights, and エ drawn as 土).
  2. The paper ground is cut away: only paper-coloured pixels connected to the border become transparent, so enclosed
     pale areas (the snow cap) stay; the edge alpha is soft and the colour is un-blended from the paper.
  3. Writes public/v3/fuji/plate-l.webp (full size) and plate-s.webp (800 wide), plus content/fuji-art.json: crop size,
     ground and summit rows (the altitude scale), the staff's x range, and both ridge lines every 4 px (the boar walks
     the left ridge; labels sit outside the slopes). The page reads only that JSON; nothing is typed twice.
usage: python3 scripts/export-fuji-art.py [source]"""
import json, os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/Library/CloudStorage/GoogleDrive-rogutore@gmail.com/My Drive/SNOBI/Art/Fuji/fuji-plate-source-2026-10-23.webp")
OUT = os.path.join(ROOT, "public", "v3", "fuji")

PAPER = np.array([242, 237, 227])  # measured: median of the corners, std ≤ 2
CROP = (60, 150, 1440, 1030)       # x0, y0, x1, y1 in source px: the whole drawing plus room for tower labels
GROUND, SUMMIT = 990, 207          # source rows: middle of the grass strip (0 m) and the crater rim (3,776 m)
STAFF_X = (1350, 1432)             # staff columns incl. its outline and a paper margin
# (stamp rows, clean rows) on the staff; clean rows are flipped. Painted stamps span rows 202-240 and 500-729
# (measured: dark pixels inside the staff); each patch reaches 10+ px past them so the feathered edge is clean.
PATCHES = [((190, 252), (260, 322)), ((488, 615), (255, 382)), ((600, 742), (345, 487))]  # the third overlaps the second, so its top feather blends clean into clean
FEATHER = 8

im = np.asarray(Image.open(SRC).convert("RGB")).astype(float)
assert im.shape[:2] == (1055, 1491), f"unexpected source size {im.shape[:2]}"

# 1. clean the staff
x0, x1 = STAFF_X
for (a, b), (c, d) in PATCHES:
    assert b - a == d - c, "patch heights differ"
    clean = im[c:d, x0:x1][::-1]
    w = np.ones(b - a)
    ramp = np.linspace(0, 1, FEATHER + 2)[1:-1]
    w[:FEATHER], w[-FEATHER:] = ramp, ramp[::-1]
    w = w[:, None, None]
    im[a:b, x0:x1] = im[a:b, x0:x1] * (1 - w) + clean * w

# 2. cut the paper away
diff = np.abs(im - PAPER).max(axis=2)
paperish = diff < 30
lab, _ = ndimage.label(paperish)
border = np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))
bg = np.isin(lab, border[border > 0])
alpha = np.ones(diff.shape)
alpha[bg] = np.clip((diff[bg] - 10) / 20, 0, 1)
a = np.clip(alpha, 1e-3, 1)[..., None]
rgb = np.clip((im - (1 - a) * PAPER) / a, 0, 255)
rgba = np.dstack([rgb, alpha * 255]).astype(np.uint8)

cx0, cy0, cx1, cy1 = CROP
plate = Image.fromarray(rgba[cy0:cy1, cx0:cx1], "RGBA")
os.makedirs(OUT, exist_ok=True)
plate.save(os.path.join(OUT, "plate-l.webp"), "WEBP", quality=86, method=6)
small = plate.resize((800, round(plate.height * 800 / plate.width)), Image.LANCZOS)
small.save(os.path.join(OUT, "plate-s.webp"), "WEBP", quality=86, method=6)

# 3. geometry: the ridge lines, traced down from the crater rim. Each row looks for the outermost dark outline pixel
# within a small window of the row above (the slope only widens downward), so a gap in the hand-drawn line or a dark
# patch of paint cannot make the trace jump; a row with no hit keeps the previous x.
lum = im.mean(axis=2)
ridge = {"L": [], "R": []}
prev = {"L": next(x for x in range(380, 830) if lum[SUMMIT + 2, x] < 110),
        "R": next(x for x in range(1275, 830, -1) if lum[SUMMIT + 2, x] < 110)}
for yy in range(SUMMIT + 2, 976, 4):
    row = lum[yy]
    hit_l = [x for x in range(prev["L"] - 24, prev["L"] + 4) if row[x] < 110]
    hit_r = [x for x in range(prev["R"] - 4, prev["R"] + 24) if row[x] < 110]
    prev["L"] = hit_l[0] if hit_l else prev["L"]
    prev["R"] = hit_r[-1] if hit_r else prev["R"]
    ridge["L"].append([yy - cy0, prev["L"] - cx0])
    ridge["R"].append([yy - cy0, prev["R"] - cx0])
geo = {
    "_doc": "Generated by scripts/export-fuji-art.py — do not edit. Units: px of public/v3/fuji/plate-l.webp.",
    "width": plate.width, "height": plate.height,
    "ground": GROUND - cy0, "summit": SUMMIT - cy0,
    "staff": [x0 + 8 - cx0, x1 - 8 - cx0],
    "towers": {"tokyo": 203 - cx0, "skytree": 253 - cx0},
    "ridge": ridge,
}
json.dump(geo, open(os.path.join(ROOT, "content", "fuji-art.json"), "w"), indent=1)
kb = lambda f: os.path.getsize(os.path.join(OUT, f)) // 1024
print(f"plate {plate.size} l {kb('plate-l.webp')} KB, s {kb('plate-s.webp')} KB; ridge L {len(ridge['L'])} R {len(ridge['R'])}")
