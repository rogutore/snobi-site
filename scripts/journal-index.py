#!/usr/bin/env python3
"""Regenerate content/journal/index.ts from content/journal/posts/*.ts (one import per post; never edit by hand).
Checks: file name == slug, slugs unique, cover photo exported (public/v2/photos/manifest.json). Run after adding a post."""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
POSTS = ROOT / "content/journal/posts"
manifest = json.loads((ROOT / "public/v2/photos/manifest.json").read_text())
lines, names, errors = [], [], []
for f in sorted(POSTS.glob("*.ts")):
    src = f.read_text(encoding="utf-8")
    slug = re.search(r'slug:\s*"([^"]+)"', src)
    cover = re.search(r'cover:\s*"([^"]+)"', src)
    if not slug or slug.group(1) != f.stem:
        errors.append(f"{f.name}: slug must equal the file name")
    if not cover or cover.group(1) not in manifest:
        errors.append(f"{f.name}: cover {cover.group(1) if cover else None} not in public/v2/photos/manifest.json")
    name = "p_" + re.sub(r"\W", "_", f.stem)
    names.append(name)
    lines.append(f'import {name} from "./posts/{f.stem}";')
if errors:
    sys.exit("\n".join(errors))
out = ['/* GENERATED by scripts/journal-index.py — do not edit. */', 'import type { Post } from "./types";', *lines, "",
       "/** Newest first. */",
       f"export const posts: Post[] = [{', '.join(names)}].sort((a, b) => b.published.localeCompare(a.published) || a.slug.localeCompare(b.slug));", ""]
(ROOT / "content/journal/index.ts").write_text("\n".join(out), encoding="utf-8")
print(f"{len(names)} posts → content/journal/index.ts")
