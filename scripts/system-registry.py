#!/usr/bin/env python3
"""Validate touched policy values and generate the immutable browser-safe registry.
Run normally after an intentional registry edit; --check never writes.
"""
import hashlib
import json
from pathlib import Path
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
UNITS = {"mexico_caffeine_cut": "percent", "mexico_members": "count", "orizaba_elevation_m": "m", "roast_days": "iso_weekdays", "enjoy_short": "localized_text_pair", "enjoy_long": "localized_text_pair", "free_shipping_yen": "JPY"}

def validate(raw):
    if set(raw) != {"meta", "value", "output"} or set(raw["meta"]) != {"about"}:
        raise ValueError("unknown/missing registry section")
    if set(raw["value"]) != set(UNITS):
        raise ValueError("unknown/missing registry key")
    if set(raw["output"]) != {"registry", "schedule", "enjoy_period", "shipping_threshold", "shipping_progress"}:
        raise ValueError("unknown/missing registry output")
    for key, entry in raw["value"].items():
        if set(entry) != {"value", "unit", "origin", "consumers"}:
            raise ValueError(f"{key}: invalid entry fields")
        unit, value = entry["unit"], entry["value"]
        if unit != UNITS[key]:
            raise ValueError(f"{key}: unknown/wrong unit")
        if not isinstance(entry["origin"], str) or not entry["origin"].strip():
            raise ValueError(f"{key}: missing provenance")
        valid = False
        if unit == "percent":
            valid = type(value) in (int, float) and 0 <= value <= 100
        elif unit in ("count", "m", "JPY"):
            valid = type(value) is int and value > 0
        elif unit == "iso_weekdays":
            valid = isinstance(value, list) and len(value) > 0 and all(type(x) is int and 1 <= x <= 7 for x in value) and len(set(value)) == len(value)
        elif unit == "localized_text_pair":
            valid = isinstance(value, list) and len(value) == 2 and all(isinstance(x, str) and x.strip() for x in value)
        if not valid:
            raise ValueError(f"{key}: invalid {unit} value")
        if not isinstance(entry["consumers"], list) or not entry["consumers"]:
            raise ValueError(f"{key}: missing consumers")
        for consumer in entry["consumers"]:
            if not isinstance(consumer, str) or key not in (ROOT / consumer).read_text():
                raise ValueError(f"{key}: unmapped consumer {consumer}")
    known = {"value." + key for key in raw["value"]}
    for key, output in raw["output"].items():
        if set(output) != {"derived_by", "binds_to", "reads", "consumers"}:
            raise ValueError(f"output {key}: invalid fields")
        if not output["reads"] or not output["consumers"] or not output["binds_to"]:
            raise ValueError(f"output {key}: empty binding")
        if not (ROOT / output["derived_by"].split("#")[0]).exists() or not set(output["reads"]) <= known:
            raise ValueError(f"output {key}: missing derivation/input")
        for consumer in output["consumers"]:
            if output["binds_to"] not in (ROOT / consumer).read_text():
                raise ValueError(f"output {key}: consumer disconnected: {consumer}")

def render(raw, digest):
    lines = ["// Generated by scripts/system-registry.py from system.toml; do not hand-edit.", f'export const REGISTRY_HASH = "{digest}";', "export const SYSTEM = Object.freeze({"]
    for key, entry in raw["value"].items():
        encoded = json.dumps(entry["value"], ensure_ascii=False)
        if isinstance(entry["value"], list):
            encoded = f"Object.freeze({encoded} as const)"
        lines.append(f"  {key}: {encoded},")
    return "\n".join(lines + ["});", ""])

def main():
    source = (ROOT / "system.toml").read_bytes()
    raw = tomllib.loads(source.decode())
    validate(raw)
    generated = render(raw, hashlib.sha256(source).hexdigest())
    target = ROOT / "content/system.generated.ts"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != generated:
            raise ValueError("registry output stale; run python3 scripts/system-registry.py")
    else:
        target.write_text(generated)
    print(f"PASS registry: {len(raw['value'])} typed values, consumer map, immutable output and hash")

if __name__ == "__main__":
    main()
